#!/usr/bin/env python3
"""
scaffold_notebook.py — mint a blank Monograph notebook for SELF-CONTAINED bonus content
========================================================================================

The 15 book chapters are *companion* notebooks: code only, with the prose, figures, and
equations in the book ("read side by side"). Bonus notebooks are the opposite — the
write-up lives in the notebook itself. This scaffolder emits a ready-to-fill skeleton in
the Monograph style (see TEMPLATE.md) with that difference baked in:

  * masthead eyebrow "Bonus notebook" (not "Companion notebook");
  * a topic/series eyebrow on the title (not "Chapter N");
  * a self-contained opener note (no "read alongside the book");
  * prose placeholders in every section, because narrative is first-class here;
  * a §0 Environment block, a portable fetch() helper, and Summary/References stubs.

Usage
-----
  python scaffold_notebook.py --title "Explainable AI for Binding Affinity" \\
      --eyebrow "Bonus" --sections 4 --tier advanced --out bonus/xai_binding.ipynb

Then fill the {...} placeholders, delete the first (instructions) cell, and pair the .py:
  uv run jupytext --to py:percent bonus/xai_binding.ipynb
Validate it parses:  python tools/validate_notebooks.py bonus/xai_binding.ipynb
"""
from __future__ import annotations

import argparse
import json
import sys
import uuid
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import nbedit as NB

# uv install tiers (match README / pyproject).
ENV = {
    "core": "<code>uv sync</code>",
    "advanced": "<code>uv sync --extra advanced</code>",
    "full": "<code>uv sync --extra full</code>",
}

INSTRUCTIONS = (
    "<!-- SCAFFOLD: delete this cell. This is a SELF-CONTAINED bonus notebook: the prose "
    "lives here, not in the book. Fill every {…} placeholder. Conventions (see TEMPLATE.md): "
    "narrative markdown is first-class; LaTeX renders in Jupyter/nbviewer and on GitHub via "
    "$…$ inline and $$…$$ display; figures are generated by code cells with a caption() under "
    "them, never a heading; callouts are Note / Runtime / Caution / Key result; NO em dashes "
    "and NO emoji anywhere. Run tools/validate_notebooks.py on this file and keep it green. -->"
)


def md(text: str) -> dict:
    return {"cell_type": "markdown", "id": uuid.uuid4().hex[:8], "metadata": {},
            "source": _lines(text)}


def code(text: str) -> dict:
    return {"cell_type": "code", "id": uuid.uuid4().hex[:8], "metadata": {},
            "execution_count": None, "outputs": [], "source": _lines(text)}


def _lines(text: str) -> list[str]:
    parts = text.split("\n")
    return [p + "\n" for p in parts[:-1]] + [parts[-1]]


def build(title: str, eyebrow: str, n_sections: int, tier: str, out_path: str) -> dict:
    env_cmd = ENV[tier]
    cells = [
        md(INSTRUCTIONS),
        md(NB.masthead(eyebrow="Bonus notebook")),
        md(NB.chapter_header(eyebrow, title)),
        md(NB.note_self_contained() + "\n\n" + NB.badge(out_path.lstrip("./"))),
        md(NB.objectives([f"{{Objective {i}: start with a verb, no trailing period}}"
                          for i in range(1, 4)])),
        md(NB.section(0, "Environment Setup")),
        md(NB.env_rows(
            local=f'Install <a href="https://docs.astral.sh/uv/" style="color:#A20025;">uv</a>, '
                  f"then run {env_cmd} from the repo root (Python 3.12) and launch with "
                  "<code>uv run jupyter lab</code>.",
            colab="Run the install cell below (same pinned versions), then restart the runtime.")),
        code("# Colab: install this notebook's packages, then restart the runtime.\n"
             "# !pip install -q {packages}\n\n" + NB.FETCH_DEF +
             '\n# Colab: pull any data files this notebook needs, e.g.\n'
             '# fetch("https://raw.githubusercontent.com/nrflynn2/ml-drug-discovery/main/data/{...}",\n'
             '#       "data/{...}")'),
        md(NB.subsection("Import Packages")),
        code("# {imports for this notebook}\nimport numpy as np\nimport pandas as pd"),
    ]
    for k in range(1, n_sections + 1):
        cells.append(md(NB.section(k, f"{{Section {k} title}}")))
        cells.append(md("{Write the narrative for this section here: the motivation, the idea, "
                        "and any equations, e.g. $$ \\hat{y} = f(x) $$. This is where the prose "
                        "that would have been in the book now lives.}"))
        cells.append(code(f"# {{code for section {k}}}"))
    cells.append(md(NB.backmatter("Summary") + "\n\n{A cohesive prose recap of this notebook: "
                    "what it built and the one or two things to remember. Not a bullet list.}"))
    cells.append(md(NB.backmatter("References") + "\n\n" + NB.references([
        "{Author} ({year}). <em>{Title}.</em> {Venue}."])))

    return {
        "cells": cells,
        "metadata": {
            "jupytext": {"formats": "ipynb,py:percent"},
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python", "version": "3.12"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("--title", required=True, help="notebook title (the serif h1)")
    ap.add_argument("--eyebrow", default="Bonus", help='title eyebrow, e.g. "Bonus" or a topic')
    ap.add_argument("--sections", type=int, default=3, help="number of §1..§N section stubs")
    ap.add_argument("--tier", choices=list(ENV), default="advanced", help="uv install tier")
    ap.add_argument("--out", required=True, help="output .ipynb path (repo-relative; also the badge path)")
    a = ap.parse_args()

    nb = build(a.title, a.eyebrow, a.sections, a.tier, a.out)
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(nb, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {out}  ({len(nb['cells'])} cells; {a.sections} sections; tier={a.tier})")
    print("next: fill the {...} placeholders, delete cell 0, then "
          f"`uv run jupytext --to py:percent {a.out}`")


if __name__ == "__main__":
    main()
